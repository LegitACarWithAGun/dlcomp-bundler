std::string fmtModule(luaFile file) {
    std::string output;

    // header / info
    output += std::format("--PATH: ./{}\n", std::filesystem::relative(file.path, "./").generic_string());

    // loader
    output += std::format("modules[{}] = (function()\n", file.importId);

    // body
    std::string moduleBody = file.contents;
    // replace require calls
    auto imports = file.imports;
    for (auto importIt = imports.rbegin(); importIt != imports.rend(); importIt++) {
        auto import = *importIt;
        moduleBody = overwriteLocation(moduleBody, import.location, std::format("modules[{}]", import.targetId));
    }
    // tab right
    moduleBody = "\t" + moduleBody;
    moduleBody = std::regex_replace(moduleBody, std::regex("\n"), "\n\t");
    // write to results
    output += moduleBody + "\n";

    // close
    output += "end)()";

    return output;
}

std::vector<importId> orderFilesDepthFirst(std::vector<luaFile> files, int entry) {
    std::vector<importId> output;
    std::unordered_set<importId> visitedFiles;

    std::function<void(luaFile)> recurse = [&](luaFile file) {
        visitedFiles.insert(file.importId);

        for (auto import : file.imports) {
            if (visitedFiles.contains(import.targetId)) {
                continue;
            }
            recurse(files.at(import.targetId));
        }

        output.push_back(file.importId);
    };
    recurse(files.at(entry));

    return output;
}

std::string bundleFileTree(std::vector<luaFile> files) {
    std::string output = "-- this file has been automatically generated by deadline-bundler; do not modify\n"
                         "local modules = {}";
    for (auto id : orderFilesDepthFirst(files, 0)) {
        auto file = files.at(id);
        output += std::format("\n\n{}", fmtModule(file));
    }

    return output;
}
